test('idea extraction binds claims to whole original sentences and rejects invented sources, duplicates and oversized inputs', () => {
  const input = { taskPrompt: 'Discuss environmental problems.', completedEssay: 'Only governments can tackle large-scale environmental problems. Individuals can help locally.', existingIdeas: [] };
  const candidate = { textZh: '只有政府能解决大规模环境问题。', sourceQuote: 'Only governments can tackle large-scale environmental problems.' };
  assert.deepEqual(readIdeaCandidates({ candidates: [candidate] }, readIdeaInput(input)), [candidate]);
  assert.deepEqual(readIdeaCandidates({ candidates: [] }, input), []);
  assert.equal(readIdeaCandidates({ candidates: [{ ...candidate, sourceQuote: input.completedEssay }] }, input).length, 1);
  const padded = { ...candidate, sourceQuote: candidate.sourceQuote + ' ' };
  assert.equal(readIdeaCandidates({ candidates: [padded] }, { ...input, completedEssay: candidate.sourceQuote + ' ' })[0].sourceQuote, padded.sourceQuote);
  assert.throws(() => readIdeaCandidates({ candidates: [padded] }, { ...input, completedEssay: candidate.sourceQuote }));
  for (const sourceQuote of ['governments can tackle large-scale environmental problems.', 'Governments solve all problems.', 'Only governments can tackle large-scale environmental problems']) assert.throws(() => readIdeaCandidates({ candidates: [{ ...candidate, sourceQuote }] }, input));
  assert.throws(() => readIdeaCandidates({ candidates: [candidate, candidate] }, input));
  assert.throws(() => readIdeaCandidates({ candidates: [candidate] }, { ...input, existingIdeas: [candidate.textZh] }));
  assert.throws(() => readIdeaCandidates({ candidates: [{ ...candidate, extra: true }] }, input));
  for (const bad of [{ ...input, completedEssay: '' }, { ...input, completedEssay: 'x'.repeat(20001) }, { ...input, existingIdeas: null }, { ...input, extra: true }]) assert.throws(() => readIdeaInput(bad));
});

test('saved edits require fresh source review; late quality cannot approve a new revision or resurrect deleted ideas', async () => {
  const now = '2026-09-10T15:00:00.000Z', sourceQuote = 'Only governments can tackle large-scale environmental problems.';
  const value = { assetId: 'idea-1', sourceDocumentId: 'doc', sourceCompletionId: 'c1', textZh: '只有政府能解决大规模环境问题。', sourceQuote };
  const first = saveIdeaAsset([], value, sourceQuote, now);
  assert(isIdeaAssets(first));
  assert.equal(first[0].quality, 'unreviewed');
  const result = { version: 1, callCount: 1, assetId: 'idea-1', revision: 1, quality: 'usable', checkedAt: now, promptVersion: 'vnext-idea-quality-v1-source-scope' , model: 'test-model'};
  const approved = applyIdeaQuality(first, result); assert.equal(approved[0].qualityReview.model, 'test-model');
  assert.equal(approved[0].quality, 'usable');
  const edited = saveIdeaAsset(approved, { ...value, textZh: '只有政府能解决所有环境问题。' }, sourceQuote, now);
  assert.equal(edited[0].revision, 2);
  assert.equal(edited[0].quality, 'unreviewed');
  assert.equal(edited[0].qualityReview, undefined);
  assert.deepEqual(applyIdeaQuality(edited, result), edited);
  assert.deepEqual(applyIdeaQuality([], result), []);
  assert.throws(() => saveIdeaAsset(first, { ...value, assetId: 'other' }, sourceQuote, now));
  assert.throws(() => saveIdeaAsset(first, value, 'Unrelated text.', now));
  assert(!isIdeaAssets([{ ...approved[0], revision: 2 }]));
  assert(isIdeaAnalysis({ status: 'ready', attemptId: 't1', meta: { callCount: 1, promptVersion: 'vnext-idea-extract-v1-source-scope', model: 'test', latencyMs: 1 }, candidates: [{ textZh: value.textZh, sourceQuote, decision: 'saved', assetId: 'idea-1' }] }, sourceQuote));
  assert(!isIdeaAnalysis({ status: 'ready', attemptId: 't1', candidates: [{ textZh: value.textZh, sourceQuote, decision: 'saved' }] }, sourceQuote));
  const rejected = await checkIdeaQuality({ assetId: 'idea-1', revision: 1, textZh: value.textZh, sourceQuote, sourceEssay: 'Unrelated text.' });
  assert.equal(rejected.result.quality, 'unusable');
  assert.equal(rejected.meta.callCount, 0);
  const missing = await checkIdeaQuality({ assetId: 'idea-1', revision: 1, textZh: value.textZh, sourceQuote, sourceEssay: null });
  assert.equal(missing.result.quality, 'unknown', 'a preserved quote cannot stand in for a deleted full source');
  assert.equal(missing.meta.callCount, 0);
  const request = value => new Request('http://localhost/api/test', { method: 'POST', body: JSON.stringify(value) });
  assert.equal((await extractionPOST(request({ taskPrompt: '', completedEssay: sourceQuote, existingIdeas: [] }))).status, 400);
  const safe = await (await qualityPOST(request({ assetId: 'idea-1', revision: 2, textZh: value.textZh, sourceQuote, sourceEssay: null }))).json();
  assert.equal(safe.quality, 'unknown');
  assert.deepEqual(Object.keys(safe).sort(), ['assetId', 'callCount', 'checkedAt', 'model', 'promptVersion', 'quality', 'revision', 'version']);
  const doc = completeWriting(createEssayDocument('doc', now, { taskPrompt: 'Discuss environment.', essay: sourceQuote }), 'c1', now);
  doc.completions[0].ideas = { status: 'loading', attemptId: 't1', candidates: [] };
  const library = { assets: [], exposures: [], sequence: 0, ideas: approved };
  const workspace = { version: 2, activeDocumentId: 'doc', documents: [doc], assetLibrary: library, savedAt: now };
  assert(isPersistedWorkspace(workspace));
  assert.equal(recoverWorkspace(workspace).documents[0].completions[0].ideas.status, 'error');
  assert.equal(recoverWorkspace(workspace).assetLibrary.ideas[0].textZh, value.textZh);
  assert.equal(deleteAssetSource(library, 'doc', true).ideas.length, 1);
  assert.equal(deleteAssetSource(library, 'doc', false).ideas.length, 0);
});
