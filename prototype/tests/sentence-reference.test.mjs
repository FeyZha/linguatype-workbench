import assert from 'node:assert/strict';
import test from 'node:test';
import { REFERENCE_VERSION, readReferenceInput, readReferenceResult, readReferenceResponse, referenceKey, isReferenceRecords, finishReference } from '../app/sentence-reference.ts';
import { createEssayDocument, isPersistedWorkspace, recoverWorkspace, addHelpExposure, removeAssetHelp } from '../app/workspace-state.ts';
import { completeWriting } from '../app/writing-completion.ts';
import { POST } from '../app/api/sentence-reference/route.ts';

test('single reference contract retains empty essay and separate attempt, rejects off-target/multi-sentence input and output', () => {
  const input = { version: REFERENCE_VERSION, mode: 'intent', taskPrompt: 'Should cities improve public transport?', fullEssay: '', target: '政府应该改善公交服务', englishAttempt: '' };
  assert.deepEqual(readReferenceInput(input), input);
  const mixed = { ...input, mode: 'mixed', fullEssay: 'Cities should 改善公交服务.', target: 'Cities should 改善公交服务.' };
  assert.deepEqual(readReferenceInput(mixed), mixed);
  for (const bad of [{ ...input, taskPrompt: '' }, { ...input, target: 'English only.' }, { ...input, target: '一个意思。另一个意思。' }, { ...input, extra: true }, { ...mixed, fullEssay: '' }, { ...mixed, englishAttempt: 'something else' }]) assert.throws(() => readReferenceInput(bad), /INVALID_INPUT/);
  assert.equal(readReferenceResult({ kind: 'reference', sentence: 'Governments should improve public transport services.', questionZh: null }).kind, 'reference');
  assert.equal(readReferenceResult({ kind: 'clarification', sentence: null, questionZh: '这里指谁采取行动？' }).kind, 'clarification');
  for (const sentence of ['一句中文。', 'One sentence. Another sentence.', '', 'One\nAnother']) assert.throws(() => readReferenceResult({ kind: 'reference', sentence, questionZh: null }), /INVALID_OUTPUT/);
  assert.throws(() => readReferenceResult({ kind: 'clarification', sentence: 'An answer.', questionZh: '哪一个？' }), /INVALID_OUTPUT/);
});

test('reference snapshots survive completion/recovery and stale results cannot restore deleted or newer attempts; API stays sanitized', async t => {
  const input = { version: REFERENCE_VERSION, mode: 'intent', taskPrompt: 'Should cities improve transport?', fullEssay: '', target: '政府应该改善公交服务', englishAttempt: '' };
  const now = '2026-09-10T15:00:00.000Z';
  const response = { version: REFERENCE_VERSION, result: { kind: 'reference', sentence: 'The government should improve public transport services.', questionZh: null }, meta: { callCount: 1, model: 'test', promptVersion: 'vnext-sentence-reference-v5-existing-subject', latencyMs: 1 } };
  readReferenceResponse(response);
  const pending = { referenceId: 'r1', requestToken: 't1', input, requestedAt: now, status: 'loading', response: null, continued: false, shownAt: null };
  assert(isReferenceRecords([pending]));
  assert(!isReferenceRecords([pending, { ...pending, referenceId: 'r2' }]));
  assert.equal(referenceKey(input), referenceKey({ englishAttempt: '', ...input }));
  assert.equal(finishReference([pending], 'r1', 'old', response)[0].status, 'loading');
  assert.deepEqual(finishReference([], 'r1', 't1', response), []);
  const finished = finishReference([pending], 'r1', 't1', response);
  assert(isReferenceRecords(finished));
  assert.equal(finishReference(finished, 'r1', 't1', null)[0].status, 'ready');
  const document = { ...createEssayDocument('doc', now, { taskPrompt: input.taskPrompt, essay: 'My own writing remains here.' }), references: [pending] };
  const completed = completeWriting(document, 'c1', now);
  assert.equal(addHelpExposure(document, 'unrelated', { requestToken: 'other', itemId: 'i1', kind: 'new_direct', content: 'an expression', shownAt: now }).references[0].status, 'loading', 'normal help exposure must not run recovery');
  assert.equal(removeAssetHelp(completed, 'unrelated').references[0].status, 'loading');
  assert.equal(removeAssetHelp(completed, 'unrelated').completions[0].references[0].status, 'loading');
  document.references[0] = finished[0];
  assert.equal(completed.completions[0].references[0].status, 'loading', 'completion keeps its own snapshot');
  const workspace = { version: 2, activeDocumentId: 'doc', savedAt: now, documents: [completed] };
  assert(isPersistedWorkspace(workspace));
  const recovered = recoverWorkspace(workspace);
  assert.equal(recovered.documents[0].completions[0].references[0].status, 'error');
  assert.equal(recovered.documents[0].essay, document.essay);
  assert.equal(finishReference(recovered.documents[0].completions[0].references, 'r1', 't1', response)[0].status, 'error');
  completed.completions[0].references[0].input.target = 'two. English sentences.';
  assert(!isPersistedWorkspace(workspace));
  const settings = { base_url: 'https://example.invalid', api_key: 'test-only', model: 'test', provider: 'deepseek' };
  const previous = Object.fromEntries(Object.keys(settings).map(k => [k, process.env[k]]));
  Object.assign(process.env, settings);
  t.after(() => { for (const [k, v] of Object.entries(previous)) if (v === undefined) delete process.env[k]; else process.env[k] = v; });
  let calls = 0, output = response.result;
  t.mock.method(globalThis, 'fetch', async (_path, options) => {
    calls++;
    const sent = JSON.parse(options.body);
    assert.deepEqual(JSON.parse(sent.messages[1].content), input);
    return Response.json({ choices: [{ message: { tool_calls: [{ function: { name: 'return_sentence_reference', arguments: JSON.stringify(output) } }] } }] });
  });
  const request = body => new Request('http://localhost/api/sentence-reference', { method: 'POST', body: JSON.stringify(body) });
  assert.equal((await POST(request({ ...input, fullEssay: null }))).status, 400);
  assert.equal(calls, 0);
  const result = await POST(request(input));
  assert.equal(result.status, 200);
  const body = await result.json();
  assert.deepEqual(Object.keys(body).sort(), ['meta', 'result', 'version']);
  readReferenceResponse(body);
  output = { kind: 'reference', sentence: 'First sentence. Second sentence.', questionZh: null };
  const invalid = await POST(request(input));
  assert.equal(invalid.status, 502);
  assert.deepEqual(await invalid.json(), { error: 'REFERENCE_UNAVAILABLE' });
});
