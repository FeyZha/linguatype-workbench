import assert from 'node:assert/strict';
import test from 'node:test';
import { composeHelp, visibleHelp } from '../../evals/expression-scaffold/experiments/vnext-help.ts';
import { lockedMatchItems } from '../../evals/expression-scaffold/experiments/vnext-matching.ts';

test('fixed old/new help preserves positions, hides old English and protects request snapshots', async () => {
  const targetSentence = 'Cities should 缓解拥堵 and 缓解拥堵.';
  const asset = { assetId: 'a1', meaningZh: '缓解拥堵', expression: 'ease congestion', conditions: '参照原句', sourceQuote: 'Buses ease congestion.', type: 'language', confirmed: true, quality: 'usable', deleted: false };
  const input = { taskPrompt: 'Transport', fullEssay: targetSentence, targetSentence, items: lockedMatchItems(targetSentence), assets: [asset] };
  const full = input.items.map(item => ({ itemId: item.itemId, assetId: 'a1', coverage: 'full' }));
  let calls = 0;
  const generate = async request => {
    calls++;
    assert.deepEqual(request, { taskPrompt: input.taskPrompt, fullEssay: targetSentence, targetSentence });
    return Response.json({ items: input.items.map((item, i) => ({ sourceZh: item.sourceZh, action: 'provide_expression', recommendedExpression: `new expression ${i}`, scaffolds: [] })), memoryMatchIds: [], meta: { requestId: crypto.randomUUID(), callCount: 1, latencyMs: 0, model: 'test', promptVersion: 'expression-scaffold-v7-expression-memory-v1' } }, { headers: { 'x-linguatype-api-version': '1.0.0' } });
  };
  const old = await composeHelp(input, full, generate);
  assert.equal(calls, 0);
  assert.equal(old.meta.generationCalls, 0);
  assert(!JSON.stringify(visibleHelp(old.items)).includes('ease congestion'));
  assert(!JSON.stringify(visibleHelp(old.items)).includes('Buses'));
  assert.equal(visibleHelp(old.items, ['i2'])[1].expression, 'ease congestion');
  assert.equal(visibleHelp(old.items, ['i2'])[0].expression, undefined);
  const mixed = [full[0], { ...full[1], coverage: 'partial' }];
  const pending = composeHelp(input, mixed, generate);
  asset.expression = 'changed after request';
  const result = await pending;
  assert.equal(calls, 1);
  assert.deepEqual(result.items.map(i => i.kind), ['saved', 'new']);
  assert.equal(result.items[0].expression, 'ease congestion');
  assert.equal(result.items[1].scaffold.recommendedExpression, 'new expression 1');
  assert(!JSON.stringify(result).includes('new expression 0'));
  const allNew = await composeHelp(input, full.map(m => ({ ...m, assetId: null, coverage: 'none' })), generate);
  assert(allNew.items.every(i => i.kind === 'new'));
  assert.equal(calls, 2);
  const complex = [{ itemId: 'i1', sourceZh: '帮助居民在工作之余参加培训', kind: 'new', scaffold: { action: 'offer_scaffolds', sourceZh: '帮助居民在工作之余参加培训', recommendedExpression: null, scaffolds: [{ scaffoldId: 's1', focusZh: '工作之余', recommendedExpression: 'outside working hours' }, { scaffoldId: 's2', focusZh: '参加培训', recommendedExpression: 'take training courses' }] } }];
  assert(!JSON.stringify(visibleHelp(complex)).includes('outside working hours'));
  const revealed = visibleHelp(complex, ['i1:s2']);
  assert.equal(revealed[0].scaffolds[0].expression, undefined);
  assert.equal(revealed[0].scaffolds[1].expression, 'take training courses');
  await assert.rejects(composeHelp(input, mixed, async () => Response.json({ error: 'provider details' })), /HELP_GENERATION_FAILED/);
  await assert.rejects(composeHelp(input, [{ ...full[0], assetId: 'invented' }, full[1]], generate));
  assert.equal(input.fullEssay, targetSentence);
});
