test('standalone intent preserves empty essay, separates attempt and rejects malformed/oversized input', () => {
  const original = { version: INTENT_ENTRY_VERSION, taskPrompt: 'Should governments fund public transport?', fullEssay: '', intentZh: '缓解拥堵', englishAttempt: 'Governments could', assets: [] };
  const { input, matching } = adaptIntentInput(original);
  assert.equal(input.fullEssay, '');
  assert.equal(matching.targetSentence, original.intentZh);
  assert.deepEqual(matching.items, [{ itemId: 'i1', sourceZh: '缓解拥堵' }]);
  assert(matching.fullEssay.includes('actual_essay_json: ""'));
  assert(matching.fullEssay.includes('english_attempt_json: "Governments could"'));
  input.englishAttempt = 'changed';
  assert.equal(original.englishAttempt, 'Governments could');
  const direct = readIntentScaffolds({ items: [{ itemId: 'i1', sourceKind: 'phrase', units: [{ focusZh: '缓解拥堵', recommendedExpression: 'ease congestion' }] }] }, original);
  assert.equal(visibleHelp(direct.items)[0].expression, 'ease congestion');
  const complex = readIntentScaffolds({ items: [{ itemId: 'i1', sourceKind: 'proposition', units: [{ focusZh: '远程办公', recommendedExpression: 'remote working' }, { focusZh: '或加剧孤独感', recommendedExpression: 'potentially greater loneliness' }] }] }, { ...original, intentZh: '远程办公或加剧孤独感' });
  assert(!JSON.stringify(visibleHelp(complex.items)).includes('remote working'));
  assert.equal(visibleHelp(complex.items, ['i1:s1'])[0].scaffolds[0].expression, 'remote working');
  const semanticLabel = readIntentScaffolds({ items: [{ itemId: 'i1', sourceKind: 'proposition', units: [{ focusZh: '自动化', recommendedExpression: 'automation' }, { focusZh: '可能对招聘产生影响', recommendedExpression: 'a possible effect on hiring' }] }] }, { ...original, intentZh: '自动化可能影响招聘' });
  assert(isIntentScaffoldItem(semanticLabel.items[0].scaffold));
  assert(!isScaffoldItem(semanticLabel.items[0].scaffold));
  assert.throws(() => readIntentScaffolds({ items: [{ itemId: 'invented', units: [] }] }, original), /INVALID_OUTPUT/);
  assert.throws(() => readIntentScaffolds({ items: [{ itemId: 'i1', sourceKind: 'proposition', units: [{ focusZh: '可能', recommendedExpression: 'may' }, { focusZh: '远程办公', recommendedExpression: 'remote work' }] }] }, { ...original, intentZh: '远程办公或加剧孤独感' }), /INVALID_OUTPUT/);
  assert.throws(() => adaptIntentInput({ ...original, intentZh: '缓解拥堵。增加收入。' }), /INVALID_INPUT/);
  assert.throws(() => adaptIntentInput({ ...original, intentZh: '缓解拥堵\n增加收入' }), /INVALID_INPUT/);
  for (const change of [{ fullEssay: null }, { taskPrompt: '' }, { intentZh: 'translate this' }, { version: 'future' }, { assets: [{}] }, { extra: true }, { fullEssay: 'x'.repeat(20000) }]) assert.throws(() => adaptIntentInput({ ...original, ...change }), /INVALID_INPUT/);
});

test('intent requests retain versions and empty drafts across recovery, reject stale assets and validate the response envelope', async t => {
  const now = '2026-09-10T12:00:00.000Z';
  const input = { version: INTENT_ENTRY_VERSION, taskPrompt: 'Should governments fund public transport?', fullEssay: '', intentZh: '缓解拥堵', englishAttempt: 'Governments could', assets: [] };
  const pack = readIntentScaffolds({ items: [{ itemId: 'i1', sourceKind: 'phrase', units: [{ focusZh: '缓解拥堵', recommendedExpression: 'ease congestion' }] }] }, input);
  const meta = { model: 'test', promptVersion: 'vnext-intent-scaffold-v12-action-separation', callCount: 1, latencyMs: 10 };
  const retrieval = { outcome: 'no_candidates', waitMs: 0, requestStarted: false, completedModelCalls: 0 };
  const card = { inputVersion: INTENT_ENTRY_VERSION, cardId: 'intent1', requestToken: 'token1', intent: { intentZh: input.intentZh, englishAttempt: input.englishAttempt }, generationMeta: null, request: { taskPrompt: input.taskPrompt, essay: '', targetSentence: input.intentZh, requestedAt: now }, result: null, helpPackage: null, revealedScaffolds: [], feedback: null, feedbackReason: '', status: 'loading', error: null, createdAt: now };
  const document = { ...createEssayDocument('doc', now, { taskPrompt: input.taskPrompt }), intentCards: [card], intentDraft: { intentZh: '提供帮助', englishAttempt: 'Another attempt' }, activeIntentId: null };
  const workspace = { version: 2, documents: [document], activeDocumentId: 'doc', savedAt: now };
  assert(isPersistedWorkspace(workspace));
  const recovered = recoverWorkspace(workspace).documents[0];
  assert.equal(recovered.intentCards[0].status, 'error');
  assert.deepEqual(recovered.intentDraft, document.intentDraft);
  assert.equal(recovered.essay, '');
  const result = { pack, retrieval, generationMeta: meta };
  const finished = finishIntentRequest(document, 'intent1', 'token1', result, []);
  assert.equal(finished.intentCards[0].status, 'ready');
  assert.equal(finished.activeIntentId, null, 'late results do not select an old version');
  assert.deepEqual(finished.intentDraft, document.intentDraft);
  assert.equal(finished.essay, '');
  assert(isIntentCards(finished.intentCards));
  assert.equal(finishIntentRequest(document, 'intent1', 'obsolete', result, []).intentCards[0].status, 'loading');
  assert.equal(finishIntentRequest({ ...document, intentCards: [] }, 'intent1', 'token1', result, []).intentCards.length, 0);
  assert.equal(finishIntentRequest(recovered, 'intent1', 'token1', result, []).intentCards[0].status, 'error');
  assert.equal(finishIntentRequest(document, 'intent1', 'token1', null, []).intentCards[0].request.essay, '');
  const savedPack = { ...pack, meta: { generationCalls: 0 }, items: [{ itemId: 'i1', sourceZh: input.intentZh, kind: 'saved', assetId: 'asset', assetRevision: 1, meaningZh: input.intentZh, expression: 'ease congestion', conditions: '交通', sourceQuote: 'Better transport can ease congestion.' }] };
  const savedResult = { ...result, pack: savedPack, generationMeta: null };
  for (const assets of [[], [{ assetId: 'asset', revision: 2, quality: 'usable', qualityReview: { revision: 2 } }], [{ assetId: 'asset', revision: 1, quality: 'usable', qualityReview: { revision: 2 } }]]) assert.equal(finishIntentRequest(document, 'intent1', 'token1', savedResult, assets).intentCards[0].status, 'error');
  assert.equal(finishIntentRequest(document, 'intent1', 'token1', savedResult, [{ assetId: 'asset', revision: 1, quality: 'usable', qualityReview: { revision: 1 } }]).intentCards[0].status, 'ready');
  const deleted = removeAssetHelp(finishIntentRequest(document, 'intent1', 'token1', savedResult, [{ assetId: 'asset', revision: 1, quality: 'usable', qualityReview: { revision: 1 } }]), 'asset');
  assert(!JSON.stringify(deleted.intentCards).includes('ease congestion'));
  assert(!JSON.stringify(finishIntentRequest(deleted, 'intent1', 'token1', savedResult, [])).includes('ease congestion'));
  const completed = completeWriting({ ...finished, essay: 'Public transport can ease congestion.' }, 'completion', now);
  const imported = { ...workspace, documents: [completed] };
  assert(isPersistedWorkspace(imported));
  completed.completions[0].helpCards[0].inputVersion = 'corrupted';
  assert(!isPersistedWorkspace(imported), 'completed snapshots validate the same intent contract');
  let calls = 0, responseBody = { pack, generationMeta: meta };
  t.mock.method(globalThis, 'fetch', async (path, options) => {
    calls++;
    assert.equal(path, '/api/intent-help');
    assert.deepEqual(JSON.parse(options.body), { ...input, matches: null });
    return Response.json(responseBody);
  });
  assert.deepEqual(await requestHelp(input, new AbortController().signal, () => {}), result);
  assert.equal(calls, 1);
  responseBody = { pack, generationMeta: null };
  await assert.rejects(requestHelp(input, new AbortController().signal, () => {}), /INVALID_RESPONSE/);
  responseBody = { pack, generationMeta: meta, raw: 'must not be exposed' };
  await assert.rejects(requestHelp(input, new AbortController().signal, () => {}), /INVALID_RESPONSE/);
});
