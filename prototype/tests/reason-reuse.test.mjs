import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { readReasonRecallInput, readReasonRecall, readReasonReuseInput, readReasonReuseResult, readReasonReuseProof } from '../app/reason-reuse.ts';
import { recallReasons, checkReasonReuse } from '../app/server/reason-reuse.ts';
import { POST } from '../app/api/reason-reuse/route.ts';
test('reason recall only accepts eligible existing chains and reuse evidence preserves original order and source', async () => {
  const input = JSON.parse(readFileSync(new URL('../../evals/expression-scaffold/eval-sets/vnext-reason-reuse.dev.v1/cases.json', import.meta.url), 'utf8')).cases[0].input;
  const asset = input.asset, recall = readReasonRecallInput({ taskPrompt: input.taskPrompt, assets: [asset] });
  assert.deepEqual(readReasonRecall({ assetIds: [asset.assetId] }, recall), [{ assetId: asset.assetId, revision: 1 }]);
  assert.throws(() => readReasonRecall({ assetIds: ['invented'] }, recall));
  assert.throws(() => readReasonRecall({ assetIds: [asset.assetId, asset.assetId] }, recall));
  assert.throws(() => readReasonReuseInput({ ...input, asset: { ...asset, links: [] } }));
  const excluded = { ...recall, assets: [{ ...asset, quality: 'unknown' }] };
  assert.throws(() => readReasonRecall({ assetIds: [asset.assetId] }, excluded));
  assert.equal((await recallReasons(excluded)).meta.callCount, 0);
  assert.equal((await checkReasonReuse({ ...input, essay: '' })).meta.callCount, 0);
  const quote = input.essay, second = 'Governments gain legislative powers because they regulate firms.';
  const output = { complete: true, occurrences: [{ verdict: 'appropriate', quote }, { verdict: 'inappropriate', quote: second }] };
  assert.deepEqual(readReasonReuseResult(output, { essay: quote + ' ' + second }), output);
  assert.throws(() => readReasonReuseResult({ ...output, occurrences: [...output.occurrences].reverse() }, { essay: quote + ' ' + second }));
  assert.throws(() => readReasonReuseResult({ complete: true, occurrences: [{ verdict: 'appropriate', quote: asset.nodes[0].sourceQuote }] }, input));
  const proof = { complete: true, occurrences: [{ quote, connections: [{ verdict: 'missing', quote: '' }] }] };
  assert.equal(readReasonReuseProof(proof, input).occurrences[0].verdict, 'inappropriate');
  proof.occurrences[0].connections = [{ verdict: 'unknown', quote }];
  assert.equal(readReasonReuseProof(proof, input).occurrences[0].verdict, 'unknown');
  proof.occurrences[0].connections = [];
  assert.throws(() => readReasonReuseProof(proof, input));
  const bad = await POST(new Request('http://localhost/api/reason-reuse', { method: 'POST', body: JSON.stringify({ ...input, asset: { ...asset, quality: 'unknown' } }) }));
  assert.equal(bad.status, 400);
});
